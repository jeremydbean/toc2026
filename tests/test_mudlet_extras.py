"""What else Mudlet can do, done (owner, 2026-11-07: "do everything but the
encryption").

- Who the client is: telnet TTYPE with MTTS (client name, terminal, and
  capability bits) and GMCP Core.Hello; staff DNS LIST shows it, and a
  client that says it shows neither 256 colours nor true colour gets the
  nearest of the sixteen for a 256-colour name.
- Discord: External.Discord.Status with the character, level, class and
  area for a client that says it relays it.
- Sounds: Client.Media.Default and .Play for a client that plays them,
  silenced by SOUND OFF. The files are generated by tools/build_sounds.py.
- Login: Mudlet's Char.Login -- the saved name and password are typed for
  the player through the ordinary prompts, so every check still applies.
- The listing's rule: the interface's on/off command named at creation.

Wire formats are Mudlet's own, read from its source (ctelnet.cpp,
Host.cpp, TMedia.cpp, GMCPAuthenticator.cpp).
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import time
import unittest
from pathlib import Path

from live_mud import (IAC, SB, SE, WILL, DO, TELOPT_GMCP, LiveMud, create_character,
                      login, patch_player_file, skip_reason)

ROOT = Path(__file__).resolve().parents[1]
SKIP = skip_reason()
TELOPT_TTYPE = 24


def gmcp(client, package: str, payload: str = "") -> None:
    body = (package + (" " + payload if payload else "")).encode("latin-1")
    client.send_raw(bytes([IAC, SB, TELOPT_GMCP]) + body + bytes([IAC, SE]))


def gmcp_messages(client) -> list[tuple[str, str]]:
    out = []
    for raw in client.subnegotiations(TELOPT_GMCP):
        text = raw.decode("latin-1")
        package, _, payload = text.partition(" ")
        out.append((package, payload))
    return out


def wait_gmcp(client, package: str, timeout: float = 20.0, after: int = 0):
    """The first message of this package beyond the first `after` seen."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        found = [p for p in gmcp_messages(client)[after:] if p[0] == package]
        if found:
            return found[0][1]
        client.drain(0.3)
    raise AssertionError(f"no {package}; saw {[p[0] for p in gmcp_messages(client)]}")


def mudlet_hello(client, supports: str) -> None:
    """What Mudlet sends once GMCP is on (ctelnet.cpp)."""
    client.send_raw(bytes([IAC, DO, TELOPT_GMCP]))
    gmcp(client, "Core.Hello", '{ "client": "Mudlet", "version": "4.19.1"}')
    gmcp(client, "Core.Supports.Set", supports)


def quit_out(client) -> None:
    client.sync("save")
    client.send("quit")
    assert client.wait_closed(30)


class MudletSourceTests(unittest.TestCase):
    def test_the_sounds_are_built_from_the_script(self) -> None:
        run = subprocess.run([sys.executable, str(ROOT / "tools" / "build_sounds.py"), "--check"],
                             capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, run.stderr)

    def test_every_sound_the_game_plays_has_a_file(self) -> None:
        names = set()
        for path in (ROOT / "src").glob("*.c"):
            names |= set(re.findall(r'gmcp_play_sound\(\s*\w+,\s*"(\w+)"\s*\)',
                                    path.read_text(encoding="latin-1")))
        self.assertEqual(names, {"levelup", "achievement", "quest", "death", "tell", "secret"})
        for name in names:
            path = ROOT / "mudlet" / "media" / f"toc-{name}.wav"
            self.assertTrue(path.is_file(), path)
            self.assertLess(path.stat().st_size, 120_000)
        gmcp_c = (ROOT / "src" / "gmcp.c").read_text(encoding="latin-1")
        self.assertIn("raw.githubusercontent.com/jeremydbean/toc2026/main/mudlet/media/", gmcp_c)

    def test_the_login_password_is_never_logged_or_kept(self) -> None:
        comm = (ROOT / "src" / "comm.c").read_text(encoding="latin-1")
        self.assertIn("gmcp_login_forget( dclose );", comm)
        gmcp_c = (ROOT / "src" / "gmcp.c").read_text(encoding="latin-1")
        body = gmcp_c[gmcp_c.index('"Char.Login.Credentials"'):]
        body = body[:body.index("return;")]
        self.assertNotIn("log_string", body)
        self.assertIn("memset( password", body)


@unittest.skipIf(SKIP is not None, SKIP or "")
class MudletLiveTests(unittest.TestCase):

    def test_client_detection_and_the_colour_fallback(self) -> None:
        with LiveMud() as mud:
            with mud.connect() as c:
                create_character(c, "Zmxstaff", "Zstaffpass1")
                quit_out(c)
            patch_player_file(mud, "Zmxstaff", Levl=70)
            with mud.connect() as c:
                create_character(c, "Zmxold", "Zoldpass12")
                quit_out(c)

            # An old 16-colour client: TTYPE answered with MTTS 1 (ANSI only).
            old = mud.connect()
            old.drain(1.0)
            self.assertTrue(old.negotiated(DO, TELOPT_TTYPE), "the game asks who the client is")
            old.send_raw(bytes([IAC, WILL, TELOPT_TTYPE]))
            for answer in (b"OLDCLIENT", b"ANSI", b"MTTS 1"):
                old.drain(0.4)
                old.send_raw(bytes([IAC, SB, TELOPT_TTYPE, 0]) + answer + bytes([IAC, SE]))
            old.buffer = "By what name art thou known? "   # read above; login() looks for it
            login(old, "Zmxold", "Zoldpass12")
            old.must("color on", "")
            old.must("color says orange", "")
            old.raw = b""
            old.sync("say hello there")
            self.assertNotIn(b"\x1b[38;5;208m", old.raw, "no 256-colour code to a client that cannot show it")
            self.assertIn(b"\x1b[33m", old.raw, "orange falls back to brown")

            with mud.connect() as staff:
                login(staff, "Zmxstaff", "Zstaffpass1")
                listing = staff.must("dns list", "Connected descriptors")
                self.assertRegex(listing, r"Zmxold .*\[OLDCLIENT\]")
                quit_out(staff)
            quit_out(old)

    def test_mudlet_login_discord_sounds_and_the_creation_line(self) -> None:
        supports = ('[ "Char 1", "Char.Skills 1", "Char.Items 1", "Room 1", '
                    '"External.Discord 1", "Client.Media 2", "Char.Login 2"]')
        with LiveMud() as mud:
            # The creation line names the interface and how to turn it off.
            with mud.connect() as c:
                create_character(c, "Zmxplayer", "Zplaypass1")
                self.assertIn("TOCGUI OFF", c.transcript)
                self.assertIn("TOCGUI ON", c.transcript)
                quit_out(c)
            with mud.connect() as c:
                create_character(c, "Zmxfriend", "Zfriendpw1")
                quit_out(c)

            # Mudlet with saved credentials: logged in through the prompts.
            m = mud.connect()
            m.expect("by what name")
            mudlet_hello(m, supports)
            offer = json.loads(wait_gmcp(m, "Char.Login.Default"))
            self.assertEqual(offer, {"type": ["password-credentials"]})
            self.assertIn(TOC_MEDIA := "mudlet/media/", wait_gmcp(m, "Client.Media.Default"))
            self.assertTrue(TOC_MEDIA)
            gmcp(m, "Char.Login.Credentials",
                 '{"account":"Zmxplayer","password":"Zplaypass1","version":1,"token_storage":true}')
            result = json.loads(wait_gmcp(m, "Char.Login.Result"))
            self.assertEqual(result, {"success": True})
            m.expect("motd", timeout=30)
            m.send("")
            m.sync("time")
            status = json.loads(wait_gmcp(m, "External.Discord.Status"))
            self.assertEqual(status["game"], "Times of Chaos")
            deadline = time.monotonic() + 20
            while "Zmxplayer" not in status.get("details", "") and time.monotonic() < deadline:
                m.drain(0.5)
                found = [json.loads(p) for k, p in gmcp_messages(m) if k == "External.Discord.Status"]
                status = found[-1]
            self.assertIn("Zmxplayer, level 1", status["details"])
            self.assertTrue(status["state"].startswith("In "), status)
            self.assertIsInstance(status["starttime"], int)

            # A tell plays the tell sound; SOUND OFF silences it.
            with mud.connect() as friend:
                login(friend, "Zmxfriend", "Zfriendpw1")
                seen = len(gmcp_messages(m))
                friend.sync("tell zmxplayer hello")
                play = json.loads(wait_gmcp(m, "Client.Media.Play", after=seen))
                self.assertEqual(play["name"], "toc-tell.wav")
                self.assertEqual(play["type"], "sound")
                self.assertIn("ON", m.must("sound", "Game sounds are"))
                m.must("sound off", "OFF")
                seen = len(gmcp_messages(m))
                friend.sync("tell zmxplayer again")
                m.sync("time")
                m.drain(1.0)
                self.assertNotIn("Client.Media.Play", [k for k, _ in gmcp_messages(m)[seen:]])
                m.must("sound on", "ON")
                quit_out(friend)
            quit_out(m)

            # A wrong saved password: refused and said so, then closed.
            bad = mud.connect()
            bad.expect("by what name")
            mudlet_hello(bad, supports)
            wait_gmcp(bad, "Char.Login.Default")
            gmcp(bad, "Char.Login.Credentials", '{"account":"Zmxplayer","password":"Znotright1"}')
            result = json.loads(wait_gmcp(bad, "Char.Login.Result"))
            self.assertEqual(result, {"success": False, "message": "Wrong password."})
            self.assertTrue(bad.wait_closed(30))

            # A name with no character: told, and left at the game's question.
            new = mud.connect()
            new.expect("by what name")
            mudlet_hello(new, supports)
            wait_gmcp(new, "Char.Login.Default")
            gmcp(new, "Char.Login.Credentials", '{"account":"Zmxnobody","password":"Zwhatever1"}')
            result = json.loads(wait_gmcp(new, "Char.Login.Result"))
            self.assertFalse(result["success"])
            self.assertIn("no character by that name", result["message"])
            new.expect("did i get that right", timeout=20)
            new.close()

            # No saved credentials: the empty hand-off, and the player types.
            typed = mud.connect()
            typed.expect("by what name")
            mudlet_hello(typed, supports)
            wait_gmcp(typed, "Char.Login.Default")
            gmcp(typed, "Char.Login.Credentials", "{}")
            typed.drain(1.0)
            self.assertNotIn("Char.Login.Result", [k for k, _ in gmcp_messages(typed)])
            typed.buffer = ""
            typed.send("Zmxplayer")
            typed.expect("password")
            typed.send("Zplaypass1")
            typed.expect("motd", timeout=30)
            typed.send("")
            typed.sync("time")
            quit_out(typed)


if __name__ == "__main__":
    unittest.main()
